const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {once} = require('node:events');
const fixture = require('./open_stage_control_fixture.cjs');
const path = require('node:path');
const root = path.resolve(__dirname, '../integrations/open-stage-control');
async function until(condition) {
    const deadline = Date.now() + 5000;
    while (!condition()) { if (Date.now() > deadline) assert.fail('Timed out waiting for controller state'); await new Promise(r => setTimeout(r, 10)); }
}
test('session uses unique widgets, explicit one-shot triggers and dedicated pages', () => {
    const session = JSON.parse(fs.readFileSync(path.join(root, 'pinol.json')));
    assert.equal(session.type, 'session');
    const ids = new Set();
    function walk(widget) {
        assert(!ids.has(widget.id), 'duplicate widget id ' + widget.id); ids.add(widget.id);
        if (widget.type === 'button' && widget.address !== '/pinol/noop') assert.equal(widget.mode, 'momentary');
        for (const child of [...(widget.widgets || []), ...(widget.tabs || [])]) walk(child);
    }
    walk(session.content);
    for (const id of ['show_tab', 'snapshots_tab', 'presets_tab', 'timelines_tab', 'layers_tab', 'connect_tab']) assert(ids.has(id));
});
test('custom module follows actual WebSocket OSC feedback without command echoes', async t => {
    const peer = fixture(); await once(peer.server, 'listening');
    let controller;
    t.after(async () => { controller?.unload(); await peer.close(); });
    const incoming = [];
    const context = {nativeRequire: require, require: file => require(path.join(root, file)), module: {exports: {}}, console, setTimeout, clearTimeout, setInterval, clearInterval,
        receive: (...args) => incoming.push(args)};
    vm.runInNewContext(fs.readFileSync(path.join(root, 'pinol.js'), 'utf8'), context, {filename: 'pinol.js'});
    controller = context.module.exports;
    const send = (address, ...values) => controller.oscOutFilter({address, args: values.map(value => ({value, type: typeof value === 'number' ? 'i' : 's'}))});
    const value = address => incoming.filter(m => m[0] === address).at(-1)?.[1];
    send('/pinol/connect', '127.0.0.1', peer.server.address().port);
    await until(() => value('/pinol/ui/online') === 1);
    assert.equal(value('/sequence/cue/current/text'), 'Start the film');
    assert.equal(value('/pinol/cue/current/continuation'), 'AUTO-FOLLOW · End + 0:00.0');
    assert.equal(value('/pinol/cue/next/continuation'), 'WAIT · GO · Manual advance');
    const cueRows = JSON.parse(incoming.filter(m => m[0] === '/EDIT' && m[1] === 'cue_items').at(-1)[2]).widgets;
    assert.equal(cueRows.length, 4);
    assert.equal(cueRows[3].widgets[1].value, 'FOLLOW\nStart + 0:02.5');
    assert.equal(cueRows[3].widgets[0].preArgs[1], '604', 'badge keeps the launch bound to its own cue');
    assert.equal(peer.commands.length, 0, 'feedback never recalls a cue');
    send('/pinol/sequence/go'); send('/pinol/recall', 'snapshots', '102');
    send('/pinol/timeline/control', '401', 'pause'); send('/pinol/sequence/cue/go', '501', '603');
    await until(() => peer.commands.length === 4);
    assert.deepEqual(peer.commands.map(m => m.address), ['/sequence/by-id/501/go', '/snapshot/by-id/102/recall', '/timeline/by-id/401/pause', '/sequence/by-id/501/cue/go']);
    assert.equal(peer.commands[3].args[0].value, '603');
    send('/pinol/library/page', 'snapshots', 1);
    const page = incoming.filter(m => m[0] === '/EDIT' && m[1] === 'snapshots_items').at(-1);
    const rows = JSON.parse(page[2]).widgets;
    assert.equal(rows.length, 6); assert.equal(rows[0].preArgs[1], '124');
    assert.equal(value('/pinol/library/snapshots/page'), '25–30 / 30');
    send('/pinol/session/ready');
    assert.equal(peer.commands.length, 4, 'late client synchronization sends no show command');
    for (const socket of peer.ws.clients) socket.close();
    await until(() => value('/pinol/ui/online') === 0);
    send('/pinol/sequence/go');
    assert.equal(peer.commands.length, 4, 'offline commands are dropped');
    assert.equal(send('/unrelated', 1).address, '/unrelated');
});
test('layer desk edits typed controls, follows feedback and rejects stale or locked targets', async t => {
    const peer = fixture(); await once(peer.server, 'listening');
    let controller;
    t.after(async () => { controller?.unload(); await peer.close(); });
    const incoming = [];
    const context = {nativeRequire: require, require: file => require(path.join(root, file)), module: {exports: {}}, console, setTimeout, clearTimeout, setInterval, clearInterval,
        receive: (...args) => incoming.push(args)};
    vm.runInNewContext(fs.readFileSync(path.join(root, 'pinol.js'), 'utf8'), context, {filename: 'pinol.js'});
    controller = context.module.exports;
    const send = (address, ...args) => controller.oscOutFilter({address, args: args.map(value => ({value}))});
    const value = address => incoming.filter(m => m[0] === address).at(-1)?.[1];
    const cards = () => JSON.parse(incoming.filter(m => m[0] === '/EDIT' && m[1] === 'layer_items').at(-1)[2]).widgets;
    const card = title => cards().find(widget => (widget.widgets?.[0]?.value || widget.widgets?.[0]?.label) === title);
    const control = title => card(title)?.widgets.find(widget => ['input', 'textarea', 'dropdown', 'switch', 'xy', 'rgb', 'text'].includes(widget.type) && widget.preArgs);
    const write = (widget, ...args) => send(widget.address, ...widget.preArgs, ...args);
    const parameterPath = suffix => '/show/layer/by-id/802/' + suffix;
    send('/pinol/connect', '127.0.0.1', peer.server.address().port);
    await until(() => value('/pinol/ui/online') === 1);
    assert.equal(value('/pinol/layer/select'), '', 'connecting does not silently select an editable layer');
    send('/pinol/layer/select', '801');
    await until(() => value('/pinol/layer/ready') === 1 && control('Opacity'));
    const stale = control('Opacity');
    write(stale, .3); await until(() => peer.commands.length === 1);
    assert.equal(peer.commands[0].address, '/show/layer/by-id/801/opacity');
    await until(() => Math.abs(incoming.filter(m => m[0] === stale.address).at(-1)?.[3] - .3) < 1e-6);
    send('/pinol/layer/select', '802');
    write(stale, .8);
    await until(() => value('/pinol/layer/ready') === 1 && control('Opacity')?.preArgs[0] === '802');
    assert.equal(peer.commands.length, 1, 'queued edits from the previous selection are refused');
    write(control('Opacity'), NaN); write(control('Type'), 'video');
    send('/pinol/layer/value/forged', '802', 'forged', .8);
    assert.equal(peer.commands.length, 1, 'invalid values, read-only fields and unknown bindings cannot write');
    peer.nodes.get(parameterPath('locked')).VALUE = [true]; peer.publishNode(parameterPath('locked'));
    await until(() => value('/pinol/layer/locked') === 1);
    write(control('Opacity'), .9); assert.equal(peer.commands.length, 1);
    write(control('Enable'), 0); await until(() => peer.commands.length === 2);
    assert.equal(peer.commands[1].address, parameterPath('enable'));
    peer.nodes.get(parameterPath('locked')).VALUE = [false]; peer.publishNode(parameterPath('locked'));
    await until(() => value('/pinol/layer/locked') === 0);
    send('/pinol/layer/section', 'color');
    const rgb = control('Add Color'); assert.equal(rgb.type, 'rgb');
    write(rgb, .2, .4, .6); await until(() => peer.commands.length === 3);
    assert.equal(peer.commands[2].address, parameterPath('add'));
    assert.deepEqual(peer.commands[2].args.map(arg => arg.type), ['f', 'f', 'f']);
    await until(() => Math.abs(incoming.filter(m => m[0] === rgb.address).at(-1)?.[4] - .4) < 1e-6);
    send('/pinol/layer/section', 'transform');
    const xy = control('Position'); assert.equal(xy.type, 'xy');
    write(xy, 120, 340); await until(() => peer.commands.length === 4);
    assert.equal(peer.commands[3].address, parameterPath('position'));
    assert.deepEqual(peer.commands[3].args.map(arg => arg.value), [120, 340]);
    const activePaths = [...peer.subscriptions.values()].flatMap(set => [...set]);
    await until(() => [...peer.subscriptions.values()].every(set => !set.has(parameterPath('add'))));
    assert(activePaths.includes('/show/state'), 'show feedback remains subscribed');
    send('/pinol/layer/section', 'fx/Blur');
    write(control('Blur radius'), 12); await until(() => peer.commands.length === 5);
    assert.equal(peer.commands[4].address, parameterPath('fx/Blur/param/radius'));
    const oldFx = control('Blur radius');
    peer.catalog.layers = peer.catalog.layers.filter(entry => entry.id !== '802');
    peer.trees.delete('/show/layer/by-id/802');
    for (const socket of peer.ws.clients) socket.send(JSON.stringify({COMMAND: 'PATH_CHANGED', DATA: '/'}));
    await until(() => value('/pinol/layer/select') === '');
    write(oldFx, 20); assert.equal(peer.commands.length, 5, 'removing the selection does not retarget another layer');
    send('/pinol/session/ready');
    assert.equal(peer.commands.length, 5, 'rebuilding the editor never echoes values as commands');
    for (const socket of peer.ws.clients) socket.close();
    await until(() => value('/pinol/ui/online') === 0);
    write(oldFx, 25); assert.equal(peer.commands.length, 5);
});
test('layer reset uses native actions and refuses stale, locked and offline requests', async t => {
    const peer = fixture(); await once(peer.server, 'listening');
    let controller;
    t.after(async () => { controller?.unload(); await peer.close(); });
    const incoming = [];
    const context = {nativeRequire: require, require: file => require(path.join(root, file)), module: {exports: {}}, console,
        setTimeout, clearTimeout, setInterval, clearInterval, receive: (...args) => incoming.push(args)};
    vm.runInNewContext(fs.readFileSync(path.join(root, 'pinol.js'), 'utf8'), context);
    controller = context.module.exports;
    const send = (address, ...args) => controller.oscOutFilter({address, args: args.map(value => ({value}))});
    const value = address => incoming.filter(message => message[0] === address).at(-1)?.[1];
    const cards = () => JSON.parse(incoming.filter(message => message[0] === '/EDIT' && message[1] === 'layer_items').at(-1)[2]).widgets;
    const card = title => cards().find(widget => (widget.widgets?.[0]?.label || widget.widgets?.[0]?.value) === title);
    const reset = title => { const heading = card(title).widgets[0]; send(heading.address, ...heading.preArgs, null); };
    const endpoint = suffix => '/show/layer/by-id/801/' + suffix;
    send('/pinol/connect', '127.0.0.1', peer.server.address().port);
    await until(() => value('/pinol/ui/online') === 1);
    send('/pinol/layer/select', '801');
    await until(() => value('/pinol/layer/ready') === 1 && card('Opacity'));
    assert.equal(card('Opacity').widgets[0].doubleTap, true);
    assert.equal(card('Type').widgets[0].type, 'text', 'read-only values have no reset action');
    const stale = card('Opacity').widgets[0];
    peer.nodes.get(endpoint('opacity')).PINOL_DEFAULT = [.75];
    reset('Opacity');
    await until(() => peer.commands.length === 1);
    assert.equal(peer.commands[0].address, endpoint('opacity/reset'));
    assert.equal(peer.commands[0].args.length, 0, 'reset requests the live server default rather than writing cached values');
    assert.equal(peer.nodes.get(endpoint('opacity')).VALUE[0], .75);
    peer.nodes.get(endpoint('locked')).VALUE = [true]; peer.publishNode(endpoint('locked'));
    await until(() => value('/pinol/layer/locked') === 1);
    reset('Opacity');
    peer.nodes.get(endpoint('locked')).VALUE = [false]; peer.publishNode(endpoint('locked'));
    await until(() => value('/pinol/layer/locked') === 0);
    send('/pinol/layer/section', 'color');
    send(stale.address, ...stale.preArgs, null);
    const rgb = card('Add Color').widgets.find(widget => widget.type === 'rgb');
    send(rgb.address, ...rgb.preArgs, .2, .4, .6);
    await until(() => peer.commands.length === 2);
    const red = card('Add Color').widgets.find(widget => widget.id.endsWith('_components')).widgets[0].widgets[0];
    send(red.address, ...red.preArgs, null);
    await until(() => peer.commands.length === 3);
    assert.deepEqual(peer.nodes.get(endpoint('add')).VALUE, [0, .4, .6]);
    reset('Add Color'); await until(() => peer.commands.length === 4);
    assert.deepEqual(peer.nodes.get(endpoint('add')).VALUE, [0, 0, 0]);
    send('/pinol/layer/section', 'source');
    reset('Caption'); await until(() => peer.commands.length === 5);
    assert.deepEqual(peer.nodes.get(endpoint('param/label')).VALUE, ['Hello']);
    const last = card('Caption').widgets[0];
    for (const socket of peer.ws.clients) socket.close();
    await until(() => value('/pinol/ui/online') === 0);
    send(last.address, ...last.preArgs, null);
    assert.equal(peer.commands.length, 5);
});
